-- BIBLIOTECA DE PLATOS DEL MENÚ SEMANAL (ampliable desde la app)
-- Ejecutar en Supabase → SQL Editor. Requiere haber ejecutado antes `supabase_clientes_acceso.sql` (usa es_profesional()).
--
--  · `platos_biblioteca`: los platos propios del profesional (nombre, momento, ingredientes línea a línea, tipos de día
--    en que se usan y nota). Los usa la pestaña «Biblioteca» y el generador de semana de `planificador-nutricional.html`.
--    Solo el profesional puede leerla y escribirla (RLS); el cliente no recibe nada de aquí.
--  · No toca ninguna tabla ni función existente. Sin esta tabla la página sigue funcionando con los 92 platos de partida
--    que lleva en el código (solo lectura).
--
-- Marcha atrás: drop table public.platos_biblioteca;
-- =====================================================================================================================

create table if not exists public.platos_biblioteca (
  id          bigint generated by default as identity primary key,
  nombre      text not null check (char_length(nombre) between 1 and 160),
  momento     text not null check (momento in ('D', 'A', 'C', 'Me', 'Ce')),   -- desayuno, almuerzo, comida, merienda, cena
  ingredientes text[] not null default '{}',                                   -- una línea por ingrediente («80 g avena»)
  dias        text[] not null default '{}',                                   -- entreno, descanso, partido, libre
  origen      text check (origen is null or char_length(origen) <= 80),        -- de quién viene («Carlos»), opcional
  nota        text check (nota is null or char_length(nota) <= 300),
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now()
);
create unique index if not exists platos_biblioteca_nombre on public.platos_biblioteca (lower(nombre), momento);

alter table public.platos_biblioteca enable row level security;
drop policy if exists "solo profesional" on public.platos_biblioteca;
create policy "solo profesional" on public.platos_biblioteca
  for all to authenticated using (public.es_profesional()) with check (public.es_profesional());

revoke all on public.platos_biblioteca from anon;
grant select, insert, update, delete on public.platos_biblioteca to authenticated;
