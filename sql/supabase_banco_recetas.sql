-- ============================================================
-- BANCO COMPARTIDO DE RECETAS Y COMIDAS (plan nutricional)
-- ============================================================
-- Ejecutar en Supabase → SQL Editor → New query → Run. Es seguro ejecutarlo más de una vez.
-- Requiere `supabase_clientes_acceso.sql` (usa es_profesional()).
--
-- Un banco de ideas compartido entre todos los clientes (como la biblioteca de platos): las recetas y las comidas guardadas
-- genéricas viven aquí; cada cliente tiene sus propias copias dentro de su menú (`menus_cliente.contenido`) y, al añadirlas,
-- el profesional elige las kcal o los macros para ese cliente. Lo privado de cada cliente (menú, compra, objetivo,
-- impresiones y vista del cliente) sigue donde estaba.
--  · `recetas_banco`: una fila por receta (nombre único sin distinguir mayúsculas). `contenido` es la receta completa
--    (momento, tiempo, raciones, ingredientes, pasos, nutrición por ración, nota, consejo y `foto`, que es una ruta dentro de
--    `banco/` en el bucket privado `fotos-clientes`).
--  · `comidas_banco`: igual para las comidas guardadas (`contenido`: nombre, nota e ingredientes).
--  Las dos son «solo profesional». Las fotos van a `fotos-clientes/banco/…`: no hace falta tocar Storage (el profesional ya
--  puede subir y leer en todo el bucket y los clientes solo ven su carpeta numérica).
-- Marcha atrás:  drop table public.recetas_banco, public.comidas_banco;
-- ============================================================

create table if not exists public.recetas_banco (
  id          bigint generated by default as identity primary key,
  nombre      text   not null check (char_length(nombre) between 1 and 120),
  contenido   jsonb  not null check (jsonb_typeof(contenido) = 'object' and pg_column_size(contenido) < 300000),
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now()
);
create unique index if not exists recetas_banco_nombre on public.recetas_banco (lower(nombre));

create table if not exists public.comidas_banco (
  id          bigint generated by default as identity primary key,
  nombre      text   not null check (char_length(nombre) between 1 and 120),
  contenido   jsonb  not null check (jsonb_typeof(contenido) = 'object' and pg_column_size(contenido) < 100000),
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now()
);
create unique index if not exists comidas_banco_nombre on public.comidas_banco (lower(nombre));

alter table public.recetas_banco enable row level security;
drop policy if exists "solo profesional" on public.recetas_banco;
create policy "solo profesional" on public.recetas_banco
  for all to authenticated using (public.es_profesional()) with check (public.es_profesional());

alter table public.comidas_banco enable row level security;
drop policy if exists "solo profesional" on public.comidas_banco;
create policy "solo profesional" on public.comidas_banco
  for all to authenticated using (public.es_profesional()) with check (public.es_profesional());
